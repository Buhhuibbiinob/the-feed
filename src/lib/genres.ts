import type { MediaType } from "@/lib/media";

// Genre, per category.
//
// A fixed list rather than a free-text field, and that is the entire
// point of the feature. Typed genres arrive as "Hip-Hop", "hip hop",
// "HipHop" and "rap", which cannot be grouped, counted, filtered or
// recommended on - so a free-text genre is a genre you cannot use for
// anything, which is the same as not having one.
//
// Everything downstream that wants to know what somebody is into is
// currently stuck with three values: music, movie_tv, photography.
// "You like movies" is not a taste. This is the smallest field that
// turns it into one.
//
// Slugs are stored, labels are displayed. Renaming a label later then
// costs nothing, while renaming a stored value costs a migration.

/**
 * A genre is a slug in a family.
 *
 * The list used to be flat: sixty-three for music, forty-four for film,
 * thirty-two for photography. That is enough to say what something
 * broadly is and not nearly enough to find anything, which is the only
 * reason the field exists - "you like electronic" is barely more of a
 * taste than "you like music". Eight hundred, in families, is a taxonomy
 * somebody can actually dig through.
 *
 * The family layer is what makes that size usable rather than a wall.
 * Nobody scrolls three hundred and sixty-nine music genres; they know
 * they want something electronic and then they want to see what is under
 * it. So the picker can group, the search can rank within a family, and
 * a shelf can say what neighbourhood a microgenre sits in.
 *
 * Every slug that was in the old flat list is still here, in a family.
 * Removing one would not delete the posts using it - it would make them
 * invisible: isGenreFor goes false, the badge stops rendering, and no
 * filter ever matches that row again. So "psychedelic" lives alongside
 * "psychedelic-rock" and "synthpop" alongside "synth-pop", which is
 * untidy and correct.
 */
