/**
 * Every genre for a category, flat, in family order.
 *
 * Derived rather than written out, so the taxonomy is stated once. This
 * is what isGenreFor, mediaTypeForGenre and the search read, all of
 * which want a flat list and none of which should have to know about
 * families.
 */
export const GENRES: Record<MediaType, readonly string[]> = {
  music: FAMILIES.music.flatMap((f) => f.genres),
  movie_tv: FAMILIES.movie_tv.flatMap((f) => f.genres),
  photography: FAMILIES.photography.flatMap((f) => f.genres),
};

/** The family a genre sits in, so a picker can group and a badge can say. */
export function familyForGenre(mediaType: MediaType, slug: string): GenreFamily | null {
  return FAMILIES[mediaType].find((f) => f.genres.includes(slug)) ?? null;
}

